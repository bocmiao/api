// Optional acceptance harness; uses an installed Playwright and real Chromium.
// Example: PLAYWRIGHT_MODULE=/path/to/playwright/index.mjs node scripts/check-source-ui.js
import assert from 'node:assert/strict';
import { mkdirSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
process.env.PREVIEW_PORT='0';
const { server }=await import('./source-preview.js');
if(!server.listening)await new Promise(r=>server.once('listening',r));
const out=resolve(process.env.UI_EVIDENCE_DIR || 'data/source-evidence');
mkdirSync(out,{recursive:true});
const base=`http://127.0.0.1:${server.address().port}`, errors=[], checks=[];
let browser;
try {
  const { chromium }=await import(process.env.PLAYWRIGHT_MODULE || 'playwright');
  browser=await chromium.launch({headless:true,...(process.env.CHROMIUM_PATH?{executablePath:process.env.CHROMIUM_PATH}:{})});
  const context=await browser.newContext({viewport:{width:1440,height:1000},reducedMotion:'reduce'});
  const page=await context.newPage();
  page.on('pageerror',e=>errors.push(e.message));
  await page.goto(base+'/__preview/admin');
  const source=page.locator('#as-websites');
  const ready=()=>source.locator('.as-pager').waitFor();
  await ready();
  assert.equal(await page.locator('.as-err').count(),0);
  assert.ok(await source.locator('tbody tr').count()>0);
  const stamp=async()=>page.evaluate(()=>{
    if(document.getElementById('synthetic-note'))return;
    const note=document.createElement('p');note.id='synthetic-note';note.textContent='合成数据验收 · 本地预览，不含生产数据';note.style.cssText='font-size:13px;color:var(--text-3);margin:0 0 10px';document.querySelector('#as-websites').prepend(note);
  });
  await stamp();
  await page.screenshot({path:out+'/desktop-full.png',fullPage:true});
  await source.screenshot({path:out+'/desktop-sources.png',style:'#topbar { visibility:hidden }'});
  await source.locator('[data-source-page]').last().click();await ready();
  assert.match(await source.innerText(),/第 2 \/ /);checks.push('desktop pagination');
  await source.getByLabel('网站域名',{exact:true}).fill('blog.example.com');
  await source.getByLabel('用户 ID',{exact:true}).fill('2');
  await source.getByLabel('Key ID',{exact:true}).fill('701');
  await source.getByLabel('接口路径',{exact:true}).fill('/api/tools/hash');
  await source.getByLabel('来源状态',{exact:true}).selectOption('conflict');
  await source.getByRole('button',{name:'查询来源',exact:true}).click();await ready();
  assert.equal(await source.locator('tbody tr').count(),1);checks.push('combined website/user/key/path/state filters');
  await source.locator('[data-source-host]').click();
  await page.locator('[data-source-attribution] .as-pager').waitFor();
  await page.locator('[data-source-requests] .as-pager').waitFor();
  const detail=page.locator('.as-source-detail');
  assert.ok((await detail.innerText()).includes('<img src=x onerror=alert(1)>'));
  assert.equal(await detail.locator('img').count(),0);checks.push('key label escaped');
  await page.locator('.modal:has(.as-source-detail)').screenshot({path:out+'/source-detail.png',animations:'disabled'});
  await detail.locator('[data-source-rid]').first().click();
  await page.locator('.modal h2').filter({hasText:/请求 preview/}).waitFor();
  assert.match(await page.locator('.modal').innerText(),/Origin/);checks.push('request detail source provenance');
  await page.locator('.modal [data-close]').click();
  await source.getByRole('button',{name:'重置筛选',exact:true}).click();await ready();
  await source.getByLabel('网站域名',{exact:true}).fill('nonexistent.example');
  await source.getByRole('button',{name:'查询来源',exact:true}).click();await ready();
  assert.match(await source.innerText(),/没有符合条件的来源/);checks.push('empty state');
  await source.screenshot({path:out+'/empty.png'});
  await page.route('**/admin/analytics/sources?**',route=>route.fulfill({status:503,contentType:'application/json',body:JSON.stringify({code:503,message:'合成加载失败，请重试'})}));
  await source.getByRole('button',{name:'查询来源',exact:true}).click();
  await source.getByRole('button',{name:'重试',exact:true}).waitFor();
  await source.screenshot({path:out+'/error.png'});
  await page.unroute('**/admin/analytics/sources?**');
  await source.getByRole('button',{name:'重试',exact:true}).click();await ready();checks.push('error and retry');
  await source.getByRole('button',{name:'重置筛选',exact:true}).click();await ready();
  for(const width of [390,320]) {
    await page.setViewportSize({width,height:844});
    await source.scrollIntoViewIfNeeded();
    assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'no page overflow at '+width);
    await stamp();await source.screenshot({path:out+`/mobile-${width}-sources.png`,style:'#topbar { visibility:hidden }'});
  }
  await page.screenshot({path:out+'/mobile-full.png',fullPage:true});checks.push('390px and 320px layouts, reduced motion');
  await source.getByLabel('网站域名',{exact:true}).fill('shop.example.com');
  await source.getByLabel('网站域名',{exact:true}).press('Enter');await ready();
  assert.equal(await source.locator('tbody tr').count(),1);checks.push('keyboard submit');
  await source.locator('[data-source-host]').click();
  await page.locator('[data-source-requests] .as-pager').waitFor();
  assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'no mobile dialog page overflow');
  await page.locator('.modal [data-close]').focus();await page.keyboard.press('Tab');
  assert.ok(await page.evaluate(()=>Boolean(document.activeElement.closest('.as-source-detail'))),'focus stays in source dialog');
  await page.locator('.modal:has(.as-source-detail)').screenshot({path:out+'/mobile-detail.png',animations:'disabled'});
  await page.keyboard.press('Escape');
  assert.equal(await page.locator('.as-source-detail').count(),0);
  assert.ok(await source.locator('[data-source-host]').evaluate(el=>el===document.activeElement));checks.push('mobile dialog, focus trap/return and Escape');
  const nonadmin=await browser.newContext();
  const p2=await nonadmin.newPage();await p2.goto(base+'/__preview/user');
  assert.equal((await nonadmin.request.get(base+'/admin/analytics/sources')).status(),403);
  assert.equal((await browser.newContext().then(c=>c.request.get(base+'/admin/analytics/sources'))).status(),401);checks.push('admin authorization in browser');
  assert.deepEqual(errors,[]);
  writeFileSync(out+'/browser-results.json',JSON.stringify({browser:await browser.version(),checks,pageErrors:errors},null,2));
  console.log(JSON.stringify({browser:await browser.version(),checks,pageErrors:errors,evidence:out},null,2));
} finally {await browser?.close();server.close();}
